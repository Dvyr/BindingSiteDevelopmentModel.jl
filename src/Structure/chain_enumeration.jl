"""
    enumerate_saw(N, filename)

Enumerate all self-avoiding chains of N bonds.
The first bond is fixed to (1,1,1).
Each subsequent bond is chosen from three possible continuations defined by the Hadamard product
of the previous bond with one of the vectors [-1,1,1], [1,-1,1], or [1,1,-1].

Each chain is written as a fixed-length packed record.
Returns the number of chains written.
"""
function enumerate_saw(N::Int, filename::String)
    N >= 1 || throw(ArgumentError("N must be at least 1"))

    origin = (0, 0, 0)
    first_position = (1, 1, 1)
    first_vector = (1, 1, 1)

    positions = Vector{NTuple{3,Int}}(undef, N + 1)
    positions[1] = origin
    positions[2] = first_position

    # The continuation choice is encoded as a 2-bit value in {0,1,2}.
    codes = Vector{UInt8}(undef, N - 1)

    occupied = Set{NTuple{3,Int}}()
    push!(occupied, origin)
    push!(occupied, first_position)

    count = 0

    open(filename, "w") do io
        function grow(bond_number::Int, endpoint, prev_vector)
            if bond_number == N
                packed = pack_directions(codes)
                write(io, packed)
                count += 1
                return
            end

            # The next step may only use the three continuations generated by multiplying the
            # current bond vector by one of the three sign-pattern vectors.
            for choice in 1:3
                next_vector = continuation_vector(prev_vector, choice)
                newpos = add_position(endpoint, next_vector)
                # if (newpos in occupied) print("Position already occupied: ", newpos, "\n") end
                if !(newpos in occupied)
                    codes[bond_number] = UInt8(choice - 1)
                    positions[bond_number + 2] = newpos

                    push!(occupied, newpos)
                    grow(bond_number + 1, newpos, next_vector)
                    delete!(occupied, newpos)
                end
            end
        end

        if N == 1
            write(io, UInt8[])
            count = 1
        else
            grow(1, first_position, first_vector)
        end
    end

    return count
end
